export const getCategories = () => {
  return Object.values(products).map(cat => ({
    id: cat.id,
    name: cat.name,
    description: cat.description,
    image: cat.image,
    itemCount: cat.items.length
  }));
};

export const getCategoryById = (id) => products[id] || null;

export const getProductById = (categoryId, productId) => {
  const category = products[categoryId];
  if (!category) return null;
  return category.items.find(item => item.id === productId) || null;
};

export const getAllProducts = () => {
  return Object.values(products).flatMap(cat =>
    cat.items.map(item => ({ ...item, category: cat.name, categoryId: cat.id }))
  );
};

export const searchProducts = (query) => {
  const q = query.toLowerCase();
  return getAllProducts().filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q)
  );
};

export default products;
